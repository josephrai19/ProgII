# Ejemplo de 3 funciones de cadena en Python

texto = "bienvenidos al laboratorio de programación"

# capitalize():
print(texto.capitalize())

# count():
cantidad_o = texto.count("o")
print("La letra 'o' aparece:", cantidad_o, "veces")

# find():
posicion = texto.find("laboratorio")
print("La palabra 'laboratorio' comienza en el índice:", posicion)